import { describe, expect, it } from 'vitest';
import { MAP, PIECES, SCOPE_CLASS, appFonts, assertStatic, diffStyles, fixedNow, inlineRemToPx, keepAttribute, piecePath, renameRefs, wrapFragment } from './fragments.mjs';

describe('pieces', () => {
  it('have unique names, a page and a visible side', () => {
    const all = [...PIECES, MAP];
    expect(new Set(all.map((p) => p.name)).size).toBe(all.length);
    for (const p of all) {
      expect(p.path).toMatch(/^\//);
      expect(['left', 'right']).toContain(p.anchor);
      expect(p.root).toBeTruthy();
    }
    expect(piecePath(PIECES.find((p) => p.name === 'year'), { ride: 'r', year: 2025 })).toBe('/years/2025');
  });

  it('pins the clock one day after the newest demo ride', () => {
    expect(fixedNow('2026-10-10')).toBe('2026-10-11T12:00:00.000Z');
    expect(fixedNow('2025-12-31')).toBe('2026-01-01T12:00:00.000Z');
    expect(() => fixedNow('soon')).toThrow();
  });
});

describe('keepAttribute', () => {
  it('drops behaviour, links, focus and id references', () => {
    for (const name of ['onclick', 'onMouseEnter', 'href', 'tabindex', 'title', 'aria-labelledby', 'aria-describedby', 'for', 'data-astro-cid-x', 'id', 'src', 'contenteditable']) {
      expect(keepAttribute(name, 'x', false), name).toBe(false);
    }
  });

  it('keeps what the app CSS selects on', () => {
    for (const name of ['class', 'style', 'data-slot', 'data-state', 'data-testid', 'aria-hidden', 'aria-pressed', 'role', 'disabled', 'type']) {
      expect(keepAttribute(name, 'x', false), name).toBe(true);
    }
  });

  it('keeps SVG geometry and ids, but only local references', () => {
    for (const name of ['id', 'd', 'viewBox', 'fill', 'clip-path', 'stroke-dasharray']) expect(keepAttribute(name, 'x', true), name).toBe(true);
    expect(keepAttribute('href', '#grad', true)).toBe(true);
    expect(keepAttribute('xlink:href', 'https://example.com/a.svg', true)).toBe(false);
    expect(keepAttribute('onload', 'x()', true)).toBe(false);
    expect(keepAttribute('tabindex', '0', true)).toBe(false);
  });
});

describe('renameRefs', () => {
  it('gives ids and chart ids stable names and rewrites every reference', () => {
    const html = '<svg><defs><linearGradient id="kpi-_r1_"></linearGradient><clipPath id="recharts1-clip"></clipPath></defs>'
      + '<path fill="url(#kpi-_r1_)" clip-path="url(&quot;#recharts1-clip&quot;)"></path><use href="#kpi-_r1_"></use></svg>'
      + '<div data-chart="chart-_r2_"></div>';
    const css = '[data-chart=chart-_r2_]{--color-a:var(--brand)}.dark [data-chart=chart-_r2_]{--color-a:red}';
    const out = renameRefs(html, css, 'load');
    expect(out.html).toBe('<svg><defs><linearGradient id="load-1"></linearGradient><clipPath id="load-2"></clipPath></defs>'
      + '<path fill="url(#load-1)" clip-path="url(#load-2)"></path><use href="#load-1"></use></svg>'
      + '<div data-chart="load-chart-1"></div>');
    expect(out.css).toBe('[data-chart=load-chart-1]{--color-a:var(--brand)}.dark [data-chart=load-chart-1]{--color-a:red}');
  });

  it('does not touch ids that merely share a prefix', () => {
    const out = renameRefs('<g id="a"></g><g id="ab"></g><p fill="url(#ab)"></p>', '', 'x');
    expect(out.html).toBe('<g id="x-1"></g><g id="x-2"></g><p fill="url(#x-2)"></p>');
  });
});

describe('inlineRemToPx', () => {
  it('converts rem in style attributes only', () => {
    expect(inlineRemToPx('<div class="grid-cols-[4.5rem_1fr]" style="grid-template-columns:1.75rem repeat(53, 1fr)"></div>'))
      .toBe('<div class="grid-cols-[4.5rem_1fr]" style="grid-template-columns:28px repeat(53, 1fr)"></div>');
  });
});

describe('assertStatic', () => {
  it('accepts plain markup with local SVG references', () => {
    expect(assertStatic('<div class="a"><svg><use href="#x-1"></use></svg></div>')).toContain('class="a"');
  });

  it.each([
    ['<script>alert(1)</script>', /<script>/],
    ['<div onclick="x()"></div>', /event handler/],
    ['<a href="/rides/1">x</a>', /a link/],
    ['<img class="x" data-src="/_astro/a.png">', /app build/],
    ['<astro-island></astro-island>', /island/],
    ['<div data-astro-cid-1></div>', /Astro attribute/],
  ])('rejects %s', (html, message) => {
    expect(() => assertStatic(html, 'x')).toThrow(message);
  });
});

describe('wrapFragment', () => {
  it('wraps the markup in the scoped, inert, hidden wrapper', () => {
    const out = wrapFragment({ name: 'load', html: '<p>613</p>', width: 271, height: 161 });
    expect(out).toContain(`<div class="${SCOPE_CLASS}" data-fragment="load" data-width="271" data-height="161" aria-hidden="true" inert><p>613</p></div>`);
    expect(out).toMatch(/^<!-- Generated by `npm run fragments`/);
  });
});

describe('appFonts', () => {
  const faces = [
    'font-family:Geist-b356f3a6e36733df;src:url("/_astro/fonts/aa.woff2") format("woff2");font-weight:100 900',
    'font-family:"Geist-b356f3a6e36733df fallback: Arial";src:local("Arial");size-adjust:104%',
    'font-family:Damion-37f5b8d8cdcb6b8e;src:url("/_astro/fonts/dd.woff2") format("woff2")',
  ];
  const root = ['--font-geist:Geist-b356f3a6e36733df,"Geist-b356f3a6e36733df fallback: Arial",sans-serif', '--font-damion:Damion-37f5b8d8cdcb6b8e,cursive'];

  it('renames the app fonts, points them at fonts/ and leaves the others out', () => {
    const out = appFonts(faces, root, ['--font-geist']);
    expect(out.faces).toEqual([
      'font-family:"Casquette UI Geist";src:url("fonts/aa.woff2") format("woff2");font-weight:100 900',
      'font-family:"Casquette UI Geist fallback: Arial";src:local("Arial");size-adjust:104%',
    ]);
    expect(out.files).toEqual([{ url: '/_astro/fonts/aa.woff2', file: 'aa.woff2' }]);
    expect(out.props).toEqual(['--font-geist:"Casquette UI Geist","Casquette UI Geist fallback: Arial",sans-serif']);
  });

  it('fails when a font variable is missing', () => {
    expect(() => appFonts(faces, root, ['--font-geist-mono'])).toThrow(/--font-geist-mono/);
  });
});

describe('diffStyles', () => {
  const row = (tag, box, font, fill) => [tag, box, font, fill];
  const props = ['font-family', 'fill'];

  it('ignores renamed fonts, renamed ids and empty boxes', () => {
    const app = [row('div', '0,0,100,20', 'Geist-b356f3a6e36733df, "Geist-b356f3a6e36733df fallback: Arial", sans-serif', 'none'), row('stop', '-5,-9,0,0', 'x', 'url("#kpi-_r1_")')];
    const frag = [row('div', '0,0,100,20', '"Casquette UI Geist", "Casquette UI Geist fallback: Arial", sans-serif', 'none'), row('stop', '-64,-200,0,0', 'x', 'url("#load-1")')];
    expect(diffStyles(app, frag, props)).toEqual([]);
  });

  it('reports real differences', () => {
    const app = [row('p', '0,0,100,20', 'a', 'none')];
    expect(diffStyles(app, [row('p', '0,0,100,24', 'a', 'none')], props)).toEqual(['#0 <p> box: 0,0,100,20 ≠ 0,0,100,24']);
    expect(diffStyles(app, [], props)).toEqual(['element count 1 ≠ 0']);
  });
});
